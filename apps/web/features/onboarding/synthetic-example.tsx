"use client";

import { useState } from "react";
import Link from "next/link";
import { MobilePageHeader } from "../../components/mobile-page-header";
import { usePreferences } from "../../components/preferences-provider";
import { ProjectSidebar } from "../projects/project-sidebar";
import { useWorkspaceShell } from "../../components/workspace-shell";
import { MarkdownRenderer } from "../conversations/markdown-renderer";

const ENGLISH_EXAMPLE = [
  "## The question",
  "",
  "A small team wants to decide whether to keep a weekly review. This is a **synthetic example**; it is not a conversation from your account.",
  "",
  "## Compare the evidence",
  "",
  "| Signal | Week 1 | Week 2 |",
  "| --- | ---: | ---: |",
  "| Follow-ups completed | 4 | 6 |",
  "| Open questions | 3 | 2 |",
  "",
  "The table can be copied as TSV or downloaded as CSV. Formula-like cells are protected by default.",
  "",
  "## Keep a reproducible note",
  "",
  "```text",
  "Decision: continue for two more weeks",
  "Review date: next Friday",
  "```",
  "",
  "A simple estimate can also be written as math:",
  "",
  "$$\\text{completion rate} = \\frac{\\text{completed follow-ups}}{\\text{planned follow-ups}}$$",
].join("\n");

const CHINESE_EXAMPLE = [
  "## 问题",
  "",
  "一个小团队想决定是否保留每周复盘。这是**合成示例**，不是你账号中的真实对话。",
  "",
  "## 对照证据",
  "",
  "| 指标 | 第 1 周 | 第 2 周 |",
  "| --- | ---: | ---: |",
  "| 已完成跟进 | 4 | 6 |",
  "| 待解决问题 | 3 | 2 |",
  "",
  "表格可以复制为 TSV 或下载为 CSV；默认会保护疑似公式文本。",
  "",
  "## 留下可复核记录",
  "",
  "```text",
  "决定：再试行两周",
  "复核时间：下周五",
  "```",
  "",
  "也可以用公式表达简单估算：",
  "",
  "$$\\text{完成率} = \\frac{\\text{已完成跟进}}{\\text{计划跟进}}$$",
].join("\n");

export function SyntheticExample() {
  const { resolvedLocale } = usePreferences();
  const zh = resolvedLocale === "zh-CN";
  const workspace = useWorkspaceShell();
  const [mobileSidebarOpenSignal, setMobileSidebarOpenSignal] = useState(0);
  const sections = [
    ["example-question", zh ? "问题" : "The question"],
    ["example-evidence", zh ? "对照证据" : "Compare the evidence"],
    ["example-note", zh ? "可复核记录" : "Reproducible note"],
  ] as const;

  const content = (
    <section className="flex min-w-0 flex-1 flex-col">
      <MobilePageHeader
        title={zh ? "合成阅读示例" : "Synthetic reading example"}
        description={zh ? "只读体验，不会创建或保存对话" : "Read-only preview; nothing is created or saved"}
        onOpenSidebar={() => workspace.embedded ? workspace.openMobileSidebar() : setMobileSidebarOpenSignal((value) => value + 1)}
        className="md:px-6"
      />
      <div className="min-h-0 flex-1 overflow-y-auto overflow-x-hidden">
        <main className="mx-auto max-w-4xl px-4 py-6 md:px-6 md:py-8">
          <div className="mb-6 flex flex-wrap items-center justify-between gap-3 border-b border-ui pb-4">
            <p className="max-w-2xl text-sm leading-6 text-secondary">
              {zh
                ? "以下内容完全由产品提供。你可以试用目录跳转与表格导出；这里的操作不会写入资料库、最近阅读、任务或批注。"
                : "This content is generated by the product. Try section navigation and table export; this page writes nothing to your library, recent items, tasks, or annotations."}
            </p>
            <Link href="/" className="btn-secondary inline-flex min-h-11 items-center px-3 text-sm">
              {zh ? "返回资料库" : "Back to library"}
            </Link>
          </div>

          <div className="grid gap-8 md:grid-cols-[12rem_minmax(0,1fr)]">
            <nav aria-label={zh ? "示例目录" : "Example contents"} className="h-fit border-y border-ui py-3 md:sticky md:top-4">
              <h2 className="mb-2 text-xs font-semibold uppercase tracking-wide text-secondary">{zh ? "本页目录" : "On this page"}</h2>
              <ol className="space-y-1">
                {sections.map(([id, label], index) => <li key={id}>
                  <a href={`#${id}`} className="flex min-h-11 items-center gap-2 text-sm text-primary hover:text-accent">
                    <span className="w-5 text-xs tabular-nums text-secondary">{index + 1}</span>{label}
                  </a>
                </li>)}
              </ol>
            </nav>
            <article className="min-w-0">
              <header className="mb-7 border-b border-ui pb-4">
                <p className="text-xs font-semibold uppercase tracking-wide text-accent">{zh ? "示例资料 · 不会保存" : "Example material · not saved"}</p>
                <h1 className="mt-2 text-2xl font-semibold text-primary">{zh ? "每周复盘：继续还是暂停？" : "Weekly review: continue or pause?"}</h1>
              </header>
              <section id="example-question" className="scroll-mt-6">
                <MarkdownRenderer text={zh ? "## 问题\n\n一个小团队想决定是否保留每周复盘。这是**合成示例**，不是你账号中的真实对话。" : "## The question\n\nA small team wants to decide whether to keep a weekly review. This is a **synthetic example**; it is not a conversation from your account."} />
              </section>
              <section id="example-evidence" className="mt-8 scroll-mt-6">
                <MarkdownRenderer text={zh
                  ? CHINESE_EXAMPLE.slice(CHINESE_EXAMPLE.indexOf("## 对照证据"), CHINESE_EXAMPLE.indexOf("## 留下可复核记录")).trim()
                  : ENGLISH_EXAMPLE.slice(ENGLISH_EXAMPLE.indexOf("## Compare the evidence"), ENGLISH_EXAMPLE.indexOf("## Keep a reproducible note")).trim()} />
              </section>
              <section id="example-note" className="mt-8 scroll-mt-6">
                <MarkdownRenderer text={zh
                  ? CHINESE_EXAMPLE.slice(CHINESE_EXAMPLE.indexOf("## 留下可复核记录")).trim()
                  : ENGLISH_EXAMPLE.slice(ENGLISH_EXAMPLE.indexOf("## Keep a reproducible note")).trim()} />
              </section>
              <p className="mt-8 border-t border-ui pt-4 text-xs leading-5 text-secondary">
                {zh
                  ? "此示例是只读体验，不支持保存批注或书签。需要整理自己的内容时，请返回资料库并明确导入资料。"
                  : "This is a read-only preview; annotations and bookmarks are not saved here. Return to the library and explicitly import your own material when ready."}
              </p>
            </article>
          </div>
        </main>
      </div>
    </section>
  );

  if (workspace.embedded) return content;
  return <main className="flex h-screen w-screen overflow-hidden bg-page text-primary"><ProjectSidebar mobileOpenSignal={mobileSidebarOpenSignal} showMobileTrigger={false} />{content}</main>;
}
